// MỞ TRANG DI SẢN

function openHeritage(key) {

    const heritage = heritageData[key];

    if (!heritage) return;

    document.getElementById("homePage").classList.add("hidden");
    document.getElementById("detailPage").classList.remove("hidden");

    document.getElementById("detailTitle").textContent =
        heritage.title;

    document.getElementById("detailSubtitle").textContent =
        heritage.subtitle;

    // TẠO MENU NỘI DUNG

    const menu = document.getElementById("detailMenu");

    menu.innerHTML = heritage.sections.map(section => `
        <a href="#${section.id}">
            ${section.title}
        </a>
    `).join("");

    // TẠO NỘI DUNG TRANG

    const content = document.getElementById("detailContent");

    content.innerHTML = heritage.sections.map(section => `
        <section id="${section.id}">
            <h2>${section.title}</h2>
            ${section.content}
        </section>
    `).join("");

    window.scrollTo({
        top: 0,
        behavior: "smooth"
    });

    history.pushState(
        { page: key },
        "",
        "#" + key
    );
}


// QUAY LẠI TRANG CHỦ

function showHome() {

    document.getElementById("detailPage").classList.add("hidden");
    document.getElementById("homePage").classList.remove("hidden");

    window.scrollTo({
        top: 0,
        behavior: "smooth"
    });

    history.pushState(
        { page: "home" },
        "",
        window.location.pathname
    );
}


// NÚT CUỘN LÊN ĐẦU TRANG

window.addEventListener("scroll", function() {

    const button = document.getElementById("topButton");

    if (window.scrollY > 400) {
        button.style.display = "block";
    } else {
        button.style.display = "none";
    }

});


// HỖ TRỢ NÚT BACK CỦA TRÌNH DUYỆT

window.addEventListener("popstate", function(event) {

    if (event.state && heritageData[event.state.page]) {
        openHeritage(event.state.page);
    } else {
        document.getElementById("detailPage").classList.add("hidden");
        document.getElementById("homePage").classList.remove("hidden");
        window.scrollTo(0, 0);
    }

});
